        p.locator('.rc', has_text='NT Matt 1:23').click(); check('Quoted: Matt 1:23' in p.inner_text('#refOpen'), f'{name} NT chip expands to one line')
        shot('isa7_parthenos')
        p.goto(B + '#/Ps/39'); p.wait_for_selector('#v7 .w')
        t = word(p, 'ὠτία', 7); p.locator('.rc', has_text='Heb 10:5').click()
