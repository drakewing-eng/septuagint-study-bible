        t = word(p, 'ποιμαίνει', 1); lw, lr = lat(); check('present' in t and 'shepherd' in t.lower() and lw == 'regit' and 'rego' in lr, f'{name} ποιμαίνει -> regit ({lw})')
        word(p, 'κύριος', 1); lw, lr = lat(); check(lw == 'Dominus', f'{name} κύριος -> Dominus ({lw})')
