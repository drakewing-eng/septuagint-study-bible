        lw, lr = lat(); check(lw == 'principio' and 'ablative singular neuter' in lr and 'principium' in lr and 'beginning' in lr, f'{name} ἀρχῇ -> principio, abl. sg. neuter, from principium ({lw})')
        check('In principio creavit' not in lr and p.locator('#latRow details.dr').count() == 1, f'{name} Vulgate verse only as collapsed line')
        p.locator('#latRow details.dr summary').click(); check(p.inner_text('#latRow .lv b') == 'principio', f'{name} verse line highlights principio')
        p.locator('.rc', has_text='Lit.').click(); check('Homer' in p.inner_text('#refOpen'), f'{name} ἀρχῇ literature ref chip (LSJ) expands')
        p.locator('#mtabs .tab', has_text='LSJ').click(); check('foundation' in p.inner_text('#mbody'), f'{name} LSJ tab switches')
        p.locator('#mtabs .tab').first.click()
        shot('gen1_arche_noun', ['#formsRow summary'])
        check(p.locator('#pdBox .pf.cur').count() >= 1, f'{name} ἀρχῇ current form highlighted')
        t = word(p, 'ἐποίησεν', 1); lw, lr = lat(); check(lw == 'creavit' and 'perfect active indicative' in lr and 'creo' in lr, f'{name} ἐποίησεν -> creavit ({lw})')
        word(p, 'θεὸς', 1); lw, lr = lat(); check(lw == 'Deus', f'{name} θεός -> Deus ({lw})')
        word(p, 'ὁ', 1); check('no Latin word' in p.inner_text('#latRow'), f'{name} article -> no Latin word')
        t = word(p, 'ἐποίησεν', 1)
        check('aorist' in t and 'active' in t and 'indicative' in t, f'{name} ἐποίησεν parse chips')
        p.locator('.chip[data-g="aorist"]').click(); check('simple whole event' in p.inner_text('#gexp'), f'{name} aorist tooltip')
        check('Reads like' not in t and 'Quoted in' not in t, f'{name} no long prose in panel')
        shot('gen1_epoiesen_verb', ['#formsRow summary'])
