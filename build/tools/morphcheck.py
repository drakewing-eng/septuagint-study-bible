#!/usr/bin/env python3
"""Independent parsing check: compare the CCAT/Eliran Wong morphological tags with Wiktionary inflection tables
(kaikki.org Wiktextract Ancient Greek dump, CC BY-SA 4.0; an independent source - forms generated by Wiktionary's grc-conj /
grc-decl templates). For a random sample of tokens: is the form in Wiktionary's tables for the SAME lemma, and does at least one
Wiktionary analysis agree with the CCAT tag? Writes tools/morphcheck_report.json and tools/morphcheck_disagreements.csv."""
import json, os, re, random, unicodedata, collections, csv, sys
HERE = os.path.dirname(os.path.abspath(__file__)); D = os.path.join(HERE, '..', 'site', 'data')
N = int(os.environ.get('MC_N', 3000)); SEED = 2026
def norm(s):
    s = unicodedata.normalize('NFD', s)
    s = s.replace('\u0300', '\u0301').replace('\u0304', '').replace('\u0306', '')
    s = unicodedata.normalize('NFC', s).lower().replace('ς', 'σ')
    return re.sub(r'[^\w]', '', s)
def strip_acc(s): return ''.join(c for c in unicodedata.normalize('NFD', s) if unicodedata.category(c) != 'Mn')
lex = json.load(open(D + '/lexicon.json')); MT = json.load(open(D + '/morph.json')); books = json.load(open(D + '/books.json'))
toks = []
for bk in books:
    for c in bk['chapters']:
        for v in json.load(open(f"{D}/{bk['id']}/{c}.json")):
            for i, t in enumerate(v[1]):
                code = MT[t[2]][0] if isinstance(t[2], int) else ''
                if code[:1] in ('N', 'A', 'V'): toks.append((bk['id'], c, v[0], i, t[0], str(t[1]), code))
random.seed(SEED); sample = random.sample(toks, N)
need = {norm(s[4]) for s in sample}; lemmas = {norm(lex[s[5]][0]) for s in sample}
idx = collections.defaultdict(list)   # form -> [(lemma, tags)]
for line in open('/workspace/src/grc_kaikki.jsonl'):
    if '"forms"' not in line: continue
    e = json.loads(line)
    lw = norm(e.get('word', ''))
    if lw not in lemmas: continue
    tense = None
    for f in e.get('forms', []):
        if f.get('source') not in ('inflection', 'declension', 'conjugation'): continue
        if 'table-tags' in f.get('tags', []):
            tt = f['form'].lower(); tense = next((x for x in ('pluperfect', 'future perfect', 'imperfect', 'perfect', 'future', 'aorist', 'present') if x in tt), None); continue
        for alt in re.split(r'[,/]\s*', f['form']):
            k = norm(alt)
            if k in need: idx[k].append((lw, set(f.get('tags', [])) | ({tense} if tense and e.get('pos') == 'verb' else set())))
    # the lemma itself (nom. sg. / 1sg pres. act. ind.)
TENSE = {'P': 'present', 'I': 'imperfect', 'F': 'future', 'A': 'aorist', 'X': 'perfect', 'Y': 'pluperfect'}
VOICE = {'A': {'active'}, 'M': {'middle'}, 'P': {'passive'}, 'E': {'middle', 'passive'}, 'D': {'middle', 'passive'}, 'O': {'middle', 'passive'}}
MOOD = {'I': 'indicative', 'S': 'subjunctive', 'O': 'optative', 'D': 'imperative', 'N': 'infinitive', 'P': 'participle'}
CASE = {'N': 'nominative', 'G': 'genitive', 'D': 'dative', 'A': 'accusative', 'V': 'vocative'}
NUM = {'S': 'singular', 'P': 'plural', 'D': 'dual'}; GEN = {'M': 'masculine', 'F': 'feminine', 'N': 'neuter'}
PER = {'1': 'first-person', '2': 'second-person', '3': 'third-person'}
def want(code):
    """CCAT code -> list of required feature-sets (any of the alternatives in each set is fine)"""
    p, _, f = code.partition('.')
    req = []
    if p == 'V':
        t, vo, mo = f[0], f[1], f[2]; req += [{TENSE[t]}, VOICE.get(vo, set()) | ({'mediopassive'} if vo in 'MPE' else set()), {MOOD[mo]}]
        if mo in 'ISOD' and len(f) >= 5: req += [{PER[f[3]]}, {NUM[f[4]]}]
        if mo == 'P' and len(f) >= 6: req += [{GEN[f[5]]}]   # Wiktionary lists participles in the nominative only
    else:
        if len(f) >= 2: req += [{CASE[f[0]]}, {NUM[f[1]]}]
        if p == 'A' and len(f) >= 3: req += [{GEN[f[2]]}]
    return [r for r in req if r]
def agree(tags, req):
    return all(r & tags for r in req)
res = collections.Counter(); dis = []
for s in sample:
    b, c, v, i, form, lid, code = s
    lem = norm(lex[lid][0]); k = norm(form)
    an = [t for (l, t) in idx.get(k, []) if l == lem]
    if not an:
        res['not_covered'] += 1; continue
    req = want(code)
    # gender is not part of Wiktionary noun tables: nouns compare case+number only; participle tables: often absent
    if code.startswith('V') and len(code) > 4 and code[4] == 'P' and not code[5:6] in ('N',):
        res['not_covered'] += 1; continue   # oblique-case participles: not in Wiktionary tables
    if any(agree(t, req) for t in an): res['agree'] += 1
    else:
        res['disagree'] += 1
        alts = sorted({' '.join(sorted(x for x in t if x not in ('table-tags',))) for t in an})[:4]
        dis.append([f'{b} {c}:{v}', form, lex[lid][0], code, MT[s[6] and [m[0] for m in MT].index(code)][1], ' | '.join(alts)])
rep = {'sample': N, 'seed': SEED, **res, 'agreement_rate_where_covered': round(res['agree'] / max(1, res['agree'] + res['disagree']), 4),
       'coverage': round((res['agree'] + res['disagree']) / N, 4)}
json.dump(rep, open(os.path.join(HERE, 'morphcheck_report.json'), 'w'), indent=1)
with open(os.path.join(HERE, 'morphcheck_disagreements.csv'), 'w', newline='', encoding='utf-8') as f:
    w = csv.writer(f); w.writerow(['ref', 'form', 'lemma', 'ccat_code', 'ccat_plain', 'wiktionary_analyses']); w.writerows(dis)
print(rep)
